    ('b0001010-0000-4000-8000-000000000001',  38,  34),   -- 89%
    ('b0001011-0000-4000-8000-000000000001',  91,  79),   -- 87%
    ('b0001013-0000-4000-8000-000000000001',  67,  58)    -- 87%
  ) as t(pid, total, yes)
