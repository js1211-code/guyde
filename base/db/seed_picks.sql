-- ---------- 2) 판정 ----------
--
-- (글, 총 표수, 무난해요 표수). 60% 하한을 아슬아슬하게 넘는 것과 넉넉히
-- 넘는 것을 섞는다 — 전부 90%대면 하한이 있다는 걸 알 수가 없다.
--
-- ⚠️ **지금은 하한에 걸리는 글이 하나도 없다.** 원래 b0001014(55%)를 일부러
--    미달로 두어 서가가 실제로 걸러내는지 눈으로 볼 수 있게 해뒀는데, 그 글을
--    지우면서 같이 빠졌다. 제일 낮은 게 b0001003의 61%라 전부 통과한다 —
--    조건이 고장 나도 화면만 봐서는 알 수 없는 상태다.
with v as (
  select device_id, row_number() over (order by device_id) as n
  from users where device_id::text like '00000000-0000-4000-8a00-%'
),
spec as (
  select * from (values
    ('b0001001-0000-4000-8000-000000000001', 214, 163),   -- 76%
    ('b0001002-0000-4000-8000-000000000001', 187, 168),   -- 90%
    ('b0001003-0000-4000-8000-000000000001',  96,  59),   -- 61% 아슬아슬
    ('b0001004-0000-4000-8000-000000000001', 142,  92),   -- 65%
