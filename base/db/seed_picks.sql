-- ---------- 4) 확인 ----------
-- 도서관 무난템 서가에 실제로 오르는 글만 센다(60% · 종료 · 10표).
-- 서가는 커뮤니티 게시판 구조를 그대로 쓰고 거르기만 한다 — 카드로
-- 정리하지 않는다. 여기 있는 건 우리가 만든 목록이 아니라 대중이 판정을
-- 끝낸 커뮤니티 글이고, 생김새가 달라지면 그 사실이 가려진다.
select count(*) as 서가에_오르는_글
  from posts_feed
 where post_type = '무난함판정'
   and is_closed
   and vote_count >= 10
   and nanhan_percent >= 60;
