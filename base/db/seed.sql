select
  ('00000000-0000-4000-8a00-' || lpad(n::text, 12, '0'))::uuid,
  (array['조용한','부지런한','성실한','느긋한','정갈한','차분한','든든한','산뜻한',
         '무던한','한결같은','소탈한','반듯한','수수한','담백한','꾸준한','말끔한']
    )[1 + (n % 16)]
  || ' ' ||
  (array['판다','수달','라쿤','곰','여우','부엉이','사슴','다람쥐','펭귄','하마',
         '너구리','고슴도치','왈라비','알파카','비버','두더지']
    )[1 + ((n / 16) % 16)]
  || ' #' || lpad(n::text, 5, '0'),
  3
from generate_series(1, 800) as n;

