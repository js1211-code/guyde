--
-- 표를 던지는 사람들. 화면에 이름이 나올 일이 없으므로 조합으로 만든다.
-- 뒤에 5자리를 붙여 유일성을 보장한다 — 앱이 발급하는 닉네임은 4자리라
-- 진짜 방문자와 부딪힐 수가 없다.
