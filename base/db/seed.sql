-- ── 왜 다시 썼나 ──────────────────────────────────────────────
-- 이전 시드는 기능 명세는 다 채웠는데 "비어 보이지는 않지만 살아 있어
-- 보이지도 않는" 상태였다. 원인은 양이 아니라 결이었다.
--
--   1) 전부 존댓말이었다. 실제 게시판은 반말·해요체·존댓말이 섞이고
--      한 글 안에서도 본문과 댓글의 톤이 다르다.
--   2) 반응이 고르게 퍼져 있었다. 진짜 커뮤니티는 극단적으로 쏠린다 —
--      댓글 10개짜리 떡밥 하나와 아무도 안 본 글 여러 개가 공존한다.
--   3) 무난함판정·선택지투표에 사진이 없었다. 사진 없이는 기능 자체가
--      성립하지 않는다. 지금은 예외 없이 붙인다.
--
-- ── 배경 유저를 대량으로 만드는 이유 ──────────────────────────
-- 투표·판정·좋아요는 (글, 기기) 한 쌍이 유일하다. 표 400개를 만들려면
-- 사람이 400명 있어야 한다. 그래서 이름 있는 등장인물 20명과 별개로
-- 배경 유저 800명을 만든다. 이들은 표만 던지고 화면에 이름이 안 나온다
-- (투표수·좋아요수는 숫자만 보이고 누가 눌렀는지는 어디에도 안 뜬다).
--
-- ── 🚨 좋아요 개수와 온도가 묶여 있다 ─────────────────────────
-- 정보공유 글 좋아요 1개 = 글쓴이 온도 +0.2다. 좋아요 147개짜리 글을
-- 만들면 글쓴이가 65도가 되는데, `experts` 행이 없으므로 고수 뱃지는
-- 안 붙는다 — "고수도 아닌데 왜 이렇게 뜨겁지"가 된다.
--   → 온도에 잡히는 `옷` 정보공유 글은 24개까지만 준다(41.3도).
--   → 많이 받은 글은 `자유` 카테고리에 둔다. calc_temperature가
--     category='자유'를 통째로 빼기 때문에 몇 개를 받든 온도가 안 오른다.
--
-- ── 사진 ─────────────────────────────────────────────────────
-- Unsplash를 쓴다. 브리프가 요구한 "형광등 밑에서 대충 찍은" 결은 아직
-- 아니다 — 생성 도구가 없어 못 만들었다. AI 사진이 준비되면 URL만
-- 갈아끼우면 되도록 다른 건 손댈 게 없게 짜뒀다.
-- ⚠️ A/B 두 장은 조명·각도가 비슷한 것끼리 짝지었다. 여기가 어긋나면
--    옷이 아니라 잘 찍힌 사진을 고르게 되어 투표가 성립하지 않는다.
--
-- 재실행 안전: 시드 유저를 지우면 글·댓글·투표가 FK로 전부 딸려 나간다.
-- 진짜 방문자(다른 UUID)는 건드리지 않는다.
