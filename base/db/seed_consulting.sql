-- ---------- 4) 고수 댓글 추천 ----------
-- 추천 1개 = 0.5도. 목표 온도에서 역산한 개수다.
--   정갈한 여우 : 댓글 6 + 추천 14 → 36.5 + 0.6 + 7.0 = 44.1
--   말쑥한 사슴 : 댓글 6 + 추천 13 → 36.5 + 0.6 + 6.5 = 43.6
--   차분한 부엉이: 댓글 4 + 추천 12 → 36.5 + 0.4 + 6.0 = 42.9
--   말끔한 하마 : 댓글 5 + 추천 11 → 36.5 + 0.5 + 5.5 = 42.5
-- 추천하는 사람은 전부 일반 시드 유저(8000 대역)라 자가 추천 트리거에 안 걸린다.
with likers as (
  select device_id, row_number() over (order by device_id) as n
  from users
  where device_id::text like '00000000-0000-4000-8000-%'
)
insert into comment_likes (comment_id, device_id)
select comment_id, device_id from (
  -- 정갈한 여우: 5+4+3+1+1+0 = 14
  select 'dddd0001-0000-4000-8000-000000000001'::uuid as comment_id, device_id from likers where n between 1 and 5
  union all select 'dddd0001-0000-4000-8000-000000000002', device_id from likers where n between 1 and 4
  union all select 'dddd0001-0000-4000-8000-000000000003', device_id from likers where n between 1 and 3
  union all select 'dddd0001-0000-4000-8000-000000000004', device_id from likers where n = 6
  union all select 'dddd0001-0000-4000-8000-000000000005', device_id from likers where n = 7

  -- 말쑥한 사슴: 5+4+2+1+1+0 = 13
  union all select 'dddd0002-0000-4000-8000-000000000001', device_id from likers where n between 1 and 5
  union all select 'dddd0002-0000-4000-8000-000000000002', device_id from likers where n between 1 and 4
  union all select 'dddd0002-0000-4000-8000-000000000003', device_id from likers where n between 1 and 2
  union all select 'dddd0002-0000-4000-8000-000000000004', device_id from likers where n = 8
  union all select 'dddd0002-0000-4000-8000-000000000005', device_id from likers where n = 9

  -- 차분한 부엉이: 5+4+2+1 = 12
  union all select 'dddd0003-0000-4000-8000-000000000001', device_id from likers where n between 1 and 5
  union all select 'dddd0003-0000-4000-8000-000000000002', device_id from likers where n between 1 and 4
  union all select 'dddd0003-0000-4000-8000-000000000003', device_id from likers where n between 1 and 2
  union all select 'dddd0003-0000-4000-8000-000000000004', device_id from likers where n = 10

  -- 말끔한 하마: 4+3+2+1+1 = 11
  union all select 'dddd0004-0000-4000-8000-000000000001', device_id from likers where n between 1 and 4
  union all select 'dddd0004-0000-4000-8000-000000000002', device_id from likers where n between 1 and 3
