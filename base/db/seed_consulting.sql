-- GUYDE 컨설팅 시드 — 고수 4명
-- schema_v2 → patch_v2_1 → patch_v2_3 → patch_v3 → patch_v3_1 → seed.sql
-- 순서로 적용한 뒤 **seed.sql 다음에** 실행한다.
--
-- ⚠️ 순서가 중요한 이유: seed.sql은 '00000000-0000-4000-8000-%' 유저를
-- 통째로 지우고 다시 넣는다. 그 유저들이 고수 댓글에 눌러둔 추천도 같이
-- 날아가서, seed.sql을 나중에 돌리면 고수 온도가 36.5 근처로 떨어진다.
--
-- 고수는 왜 별도 유저인가
--   seed.sql은 일반 유저를 전부 42.0 아래(최대 41.8)로 눌러둔다.
--   고수 문턱이 무의미해 보이지 않게 하려는 의도다.
--   고수는 그 문턱을 실제로 넘긴 사람이어야 하므로 따로 심는다.
--
-- 온도는 저장값이 아니라 calc_temperature()가 매번 계산한다.
--   온도 = 36.5 + 댓글수×0.1 + 받은 추천수×0.5   ('자유' 카테고리 제외)
-- 그래서 experts.temperature 같은 걸 박아 넣는 게 아니라,
-- 실제 댓글과 추천을 심어서 자연스럽게 42도를 넘게 만든다.
--
-- 대표 답변 3개(F-55)도 이 댓글들을 그대로 인용한다 —
-- 더미 텍스트를 따로 두면 "실제로 단 댓글"이라는 말이 거짓이 된다.
--
-- 재실행 안전: 고수 유저를 지우면 experts·댓글·추천이 FK로 딸려 나간다.
-- ============================================================

